module.exports=async window=>{
  const run=code=>window.webContents.executeJavaScript(code);
  const wait=async code=>{for(let i=0;i<120;i++){if(await run(code))return;await new Promise(resolve=>setTimeout(resolve,250));}throw Error('Desktop check timed out: '+code+'\n'+await run('document.body.innerText.slice(0,4000)')); };
  await wait('document.body.innerText.includes("GM")');
  await run('location.hash="/management"');
  await wait('document.querySelector(".gm-world-setup") !== null');
  const setup=await run('document.body.innerText');
  await run(`Array.from(document.querySelectorAll('button')).find(b=>b.innerText.includes('세계 시작')).click()`);
  await wait('document.body.innerText.includes("구단 운영실")');
  await run('location.hash="/management/office"');
  await wait('document.body.innerText.includes("계약 가능 예산") && !document.body.innerText.includes("저장하는 중")');
  const before=await run('document.body.innerText');
  await run(`Array.from(document.querySelectorAll('button')).find(b=>b.innerText==='퓨처스·3군').click()`);
  await wait('document.querySelectorAll("tbody tr").length > 30');
  const futures=await run('document.body.innerText');
  if(!futures.includes('상무')||!futures.includes('울산 웨일즈')||!futures.includes('3군'))throw Error('Futures organization missing');
  await run('location.hash="/management"');
  await wait('Array.from(document.querySelectorAll("button")).some(b=>b.innerText.includes("오늘 경기 시뮬레이션")&&!b.disabled)');
  await new Promise(resolve=>setTimeout(resolve,500));
  await run(`Array.from(document.querySelectorAll('button')).find(b=>b.innerText.includes('오늘 경기 시뮬레이션')).click()`);
  await wait('document.body.innerText.includes("2026-03-29")');
  await window.webContents.reload();
  await wait('document.body.innerText.includes("2026-03-29")');
  const after=await run('document.body.innerText');
  await window.webContents.insertCSS('.animate-fade-in { animation:none!important; opacity:1!important; transform:none!important; }');
  await new Promise(resolve=>setTimeout(resolve,250));
  const screenshot=await window.webContents.capturePage();
  require('node:fs').writeFileSync(require('node:path').join(__dirname,'../release/desktop-verified.png'),screenshot.toPNG());
  return {setup,office:before.slice(0,1000),futures:futures.slice(0,1500),afterReload:after.slice(0,2000),passed:true};
};

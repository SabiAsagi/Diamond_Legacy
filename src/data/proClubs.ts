export function buildDefaultProTeams(): Team[] {
  return INITIAL_CLUBS_META.map((meta, index) => ({
    id: index + 1,
    code: meta.code,
    name: meta.name,
    shortName: meta.shortName,
    city: meta.city,
    venue: meta.venue,
    budget: meta.budget,
    payroll: Math.floor(meta.budget * 0.65),
    fanBase: meta.fanBase,
    reputation: meta.reputation,
    primaryColor: meta.primaryColor,
    secondaryColor: meta.secondaryColor,
    wins: 0,
    draws: 0,
    losses: 0,
    runsScored: 0,
    runsAllowed: 0,
    streak: '-',
    last10: '0승 0패',
  }));
}

export function buildDefaultProPlayers(teams: Team[]): Player[] {
  const players: Player[] = [];
  let playerIdCounter = 100;

  for (const team of teams) {
    const templates = CLUB_ROSTER_SEEDS[team.code ?? ''] ?? CLUB_ROSTER_SEEDS.TWINS;
    templates.forEach((tpl, i) => {
      const isP = tpl.isPitcher;
      const baseRating = tpl.overall;
      const variation = (delta: number) => Math.max(20, Math.min(99, Math.round(baseRating + delta)));

      const player: Player = {
        id: playerIdCounter++,
        name: tpl.name,
        gender: 'male',
        age: tpl.age,
        position: tpl.pos === ('DH' as Position) ? 'LF' : tpl.pos,
        status: 'Pro',
        teamId: team.id,
        uniformNumber: (i + 1) * 3 % 99 + 1,
        highSchool: '고교 야구부',
        handedness: isP ? 'R/R' : 'R/R',
        pitchingForm: isP ? 'ThreeQuarter' : 'None',
        pitcherRole: isP ? (tpl.role ?? 'Starter') : 'None',
        battingForm: isP ? 'None' : 'Open',
        overall: baseRating,
        potential: Math.min(99, baseRating + Math.max(0, 30 - tpl.age)),
        contact: isP ? 20 : variation(Math.floor(Math.random() * 8 - 4)),
        power: isP ? 15 : variation(Math.floor(Math.random() * 8 - 4)),
        eye: isP ? 20 : variation(Math.floor(Math.random() * 6 - 3)),
        speed: isP ? 30 : variation(Math.floor(Math.random() * 10 - 5)),
        defense: isP ? 40 : variation(Math.floor(Math.random() * 6 - 3)),
        stuff: isP ? variation(Math.floor(Math.random() * 8 - 4)) : 0,
        control: isP ? variation(Math.floor(Math.random() * 6 - 3)) : 0,
        stamina: isP ? (tpl.role === 'Starter' ? variation(10) : variation(-15)) : 0,
        condition: 85 + Math.floor(Math.random() * 15),
        academics: 50,
        relationships: { ...INITIAL_RELATIONSHIPS },
        rosterTier: '1군',
        salary: Math.floor(baseRating * baseRating * 12),
        contractYears: Math.floor(Math.random() * 3) + 1,
        proStats: {
          batting: {
            games: 0,
            pa: 0,
            ab: 0,
            hits: 0,
            doubles: 0,
            triples: 0,
            hr: 0,
            rbi: 0,
            runs: 0,
            bb: 0,
            so: 0,
            sb: 0,
            avg: 0,
            obp: 0,
            slg: 0,
            ops: 0,
          },
          pitching: {
            games: 0,
            starts: 0,
            wins: 0,
            losses: 0,
            saves: 0,
            holds: 0,
            innings: 0,
            hitsAllowed: 0,
            hrAllowed: 0,
            bbAllowed: 0,
            so: 0,
            runsAllowed: 0,
            earnedRuns: 0,
            era: 0,
            whip: 0,
          },
        },
      };

      players.push(player);
    });
  }

  return players;
}
